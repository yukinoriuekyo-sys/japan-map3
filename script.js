// 地図を取得
const map = document.getElementById("map");


// 地点を1つずつ作る
locations.forEach(location => {

    // 地点全体
    const point = document.createElement("div");

    point.className = "point";


    // 地図上の位置
    point.style.left = location.left + "%";
    point.style.top = location.top + "%";


    // リンクメニューを作る
 const linkMenu = location.links.map(link => {

    // さらに下のメニューがある場合
    if (link.sublinks) {

        const subMenu = link.sublinks.map(subLink => {

            return `
                <a href="${subLink.url}" target="_blank" rel="noopener noreferrer">
                    ${subLink.name}
                </a>
            `;

        }).join("");


        return `
            <div class="menu-item has-submenu">

                <div class="menu-link">
                    ${link.name}
                    <span class="arrow">▶</span>
                </div>

                <div class="sub-menu">
                    ${subMenu}
                </div>

            </div>
        `;

    }


    // 普通のリンク
    return `
        <a href="${link.url}" target="_blank" rel="noopener noreferrer">
            ${link.name}
        </a>
    `;

}).join("");


    // HTMLを作る
    point.innerHTML = `
        <div class="point-marker">

            <!-- 丸印 -->
            <a href="#" aria-label="${location.name}"></a>

            <!-- 地点名 -->
            <span>${location.name}</span>

            <!-- 複数リンク -->
            <div class="link-menu">
                ${linkMenu}
            </div>

        </div>
    `;


    // 地図に追加
    map.appendChild(point);
document.querySelectorAll(".menu-item.has-submenu").forEach(item => {

    const menuLink = item.querySelector(".menu-link");

    menuLink.addEventListener("click", function(event) {

        // サブメニューを開く
        event.preventDefault();

        item.classList.toggle("open");

    });

});
});
